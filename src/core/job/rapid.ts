import type { WeldJob } from './schema'

type Seam = WeldJob['seams'][number]
type Quat = [number, number, number, number]

const MAX_NAME = 32
const HASH_KEEP = MAX_NAME - 5

function hash4(text: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 0x01000193)
  return (h & 0xffff).toString(16).padStart(4, '0')
}

// A RAPID identifier: letters, digits and underscores, starting with a letter, at most 32 characters.
export function rapidName(text: string): string {
  let name = text.replace(/[^A-Za-z0-9_]/g, '_')
  if (!/^[A-Za-z]/.test(name)) name = `R_${name}`
  return name.length <= MAX_NAME ? name : `${name.slice(0, HASH_KEEP)}_${hash4(text)}`
}

// Spec order is [x, y, z, w]; RAPID wants [q1, q2, q3, q4] = [w, x, y, z].
export function quaternionToRapid(q: Quat): Quat {
  const [x, y, z, w] = q
  const norm = Math.hypot(x, y, z, w) || 1
  return [w / norm, x / norm, y / norm, z / norm]
}

const fixed = (value: number, digits: number) => {
  const text = value.toFixed(digits)
  return /^-0(\.0*)?$/.test(text) ? text.slice(1) : text
}
const vec = (v: readonly number[]) => `[${v.map((n) => fixed(n, 1)).join(',')}]`
const quat = (q: Quat) => `[${quaternionToRapid(q).map((n) => fixed(n, 6)).join(',')}]`

// Comments stay on one line and free of the dash characters the project never writes.
const comment = (text: string) => text.replace(/[\u2013\u2014]/g, '-').replace(/\s+/g, ' ').trim()

const two = (n: number) => String(n).padStart(2, '0')
const three = (n: number) => String(n).padStart(3, '0')

function exclusion(seam: Seam): string | null {
  const cls = seam.access.class
  if (cls === null) return 'access not checked'
  if (cls === 'snake' || cls === 'blocked') return cls
  return seam.poses.length < 2 ? 'fewer than 2 poses' : null
}

// A template for standard and slim seams. The tool and work object are placeholders and the seam, weld and weave data
// belong to the cell, so the file says what it expects instead of defining it.
export function toRapid(job: WeldJob): string {
  const byId = new Map(job.seams.map((s) => [s.id, s]))
  const ordered = job.sequence.order.flatMap((o) => {
    const seam = byId.get(o.seamId)
    return seam ? [seam] : []
  })
  const included: Seam[] = []
  const skipped: string[] = []
  for (const seam of ordered) {
    const reason = exclusion(seam)
    if (reason === null) included.push(seam)
    else skipped.push(`${comment(seam.label)} (${comment(seam.id)}, ${reason})`)
  }

  const weaves = (seam: Seam) => job.procedures.find((p) => p.id === seam.procedureId)?.weave.pattern !== 'none'
  const names = (prefix: string, pick: (s: Seam) => boolean) => [
    ...new Set(included.filter(pick).map((s) => rapidName(`${prefix}_${s.procedureId}`))),
  ]
  const defs = [
    ['seamdata', names('sm', () => true)],
    ['welddata', names('wd', () => true)],
    ['weavedata', names('wv', weaves)],
  ] as const
  const needed = defs.filter(([, list]) => list.length > 0).map(([kind, list]) => `${kind} ${list.join(', ')}`)

  const out: string[] = [
    `MODULE ${rapidName(`WeldJob_${job.id}`)}`,
    '    ! Template, verify on a controller before running.',
    `    ! Generated by ${comment(`${job.generator.name} ${job.generator.version}`)} from ${comment(job.part.name)} at ${comment(job.createdAt)}`,
    '    ! Units mm; robtarget orientation [q1,q2,q3,q4] = [w,x,y,z]',
    `    ! Define in the cell: ${needed.length > 0 ? needed.join('; ') : 'none'}`,
    `    ! Not included: ${skipped.length > 0 ? skipped.join(', ') : 'none'}`,
    '',
    '    PERS tooldata tWeldGun := [TRUE,[[0,0,350],[1,0,0,0]],[3,[0,0,100],[1,0,0,0],0,0,0]];',
    `    PERS wobjdata wPart := [FALSE,TRUE,"",[${vec(job.frames.partToCell.position)},${quat(job.frames.partToCell.quaternion)}],[[0,0,0],[1,0,0,0]]];`,
    '',
  ]

  const target = (n: number, k: number) => `S${two(n)}_P${three(k)}`
  included.forEach((seam, i) => {
    seam.poses.forEach((pose, k) => {
      out.push(`    CONST robtarget ${target(i + 1, k)} := [${vec(pose.position)},${quat(pose.quaternion)},[0,0,0,0],[9E9,9E9,9E9,9E9,9E9,9E9]];`)
    })
  })
  if (included.length > 0) out.push('')

  out.push('    PROC main()')
  if (included.length === 0) out.push('        ! No seam is exported: none is standard or slim with two or more poses.')
  included.forEach((seam, i) => {
    const n = i + 1
    const sm = rapidName(`sm_${seam.procedureId}`)
    const wd = rapidName(`wd_${seam.procedureId}`)
    // The weave belongs on every arc instruction: an instruction without it welds straight.
    const arc = weaves(seam) ? `${sm}, ${wd}\\Weave:=${rapidName(`wv_${seam.procedureId}`)}` : `${sm}, ${wd}`
    const last = seam.poses.length - 1
    out.push(`        ! S${two(n)} = ${comment(seam.label)} (${comment(seam.id)}), ${comment(seam.procedureId)}, ${fixed(seam.lengthMm, 1)} mm`)
    out.push(`        MoveJ RelTool(${target(n, 0)},0,0,${fixed(-seam.approach.distanceMm, 1)}), v1000, z50, tWeldGun\\WObj:=wPart;`)
    out.push(`        ArcLStart ${target(n, 0)}, v100, ${arc}, fine, tWeldGun\\WObj:=wPart;`)
    for (let k = 1; k < last; k++) out.push(`        ArcL ${target(n, k)}, v100, ${arc}, z1, tWeldGun\\WObj:=wPart;`)
    out.push(`        ArcLEnd ${target(n, last)}, v100, ${arc}, fine, tWeldGun\\WObj:=wPart;`)
    out.push(`        MoveL RelTool(${target(n, last)},0,0,${fixed(-seam.retract.distanceMm, 1)}), v500, z10, tWeldGun\\WObj:=wPart;`)
  })
  out.push('    ENDPROC', 'ENDMODULE', '')
  return out.join('\n')
}
