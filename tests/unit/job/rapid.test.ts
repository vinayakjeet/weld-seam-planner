import { describe, expect, it } from 'vitest'
import { buildJob } from '../../../src/core/job/build'
import { quaternionToRapid, rapidName, toRapid } from '../../../src/core/job/rapid'
import type { SeamAccess, WeldJob } from '../../../src/core/job/schema'
import { CREATED_AT, specExamplePlan } from '../helpers/jobs'

const access = (cls: SeamAccess['class']): SeamAccess => ({
  clearanceDeg: 40,
  nearClearanceDeg: 40,
  class: cls,
  portId: null,
  reachCoverage: null,
  unreachable: [],
})

function threeSeamJob(classes: Array<SeamAccess['class']> = ['standard', 'slim', 'snake']): WeldJob {
  const plan = specExamplePlan(
    classes.map((_, i) => ({ id: `s0${i + 1}`, from: [0, 300 * i, 12], to: [200, 300 * i, 12] })),
  )
  plan.seams = plan.seams.map((p, i) => ({ ...p, access: classes[i] === null ? null : access(classes[i]!) }))
  return buildJob(plan, { createdAt: CREATED_AT })
}

const lines = (text: string) => text.split('\n').map((l) => l.trim())
const targetLines = (text: string) => lines(text).filter((l) => l.startsWith('CONST robtarget'))
const includedIds = (job: WeldJob) =>
  job.sequence.order.map((o) => o.seamId).filter((id) => ['standard', 'slim'].includes(job.seams.find((s) => s.id === id)!.access.class ?? ''))

describe('quaternionToRapid', () => {
  it('moves w to the front and keeps the spec example within 1e-4', () => {
    const out = quaternionToRapid([-0.9204, 0.0334, -0.0805, 0.3812])
    const want = [0.3812, -0.9204, 0.0334, -0.0805]
    out.forEach((v, i) => expect(Math.abs(v - want[i]!)).toBeLessThan(1e-4))
  })

  it('renormalises a quaternion that is slightly off unit length', () => {
    const out = quaternionToRapid([0, 0, 0, 1.0002])
    expect(out).toEqual([1, 0, 0, 0])
  })
})

describe('rapidName', () => {
  it('replaces characters RAPID does not allow with underscores', () => {
    expect(rapidName('WPS 1.2/A')).toBe('WPS_1_2_A')
  })

  it('gives a leading digit or underscore the R_ prefix', () => {
    expect(rapidName('1abc')).toBe('R_1abc')
    expect(rapidName('_x')).toBe('R__x')
  })

  it('cuts a long id to 32 characters with a short hash and keeps two long ids apart', () => {
    const a = rapidName('A'.repeat(40))
    const b = rapidName(`${'A'.repeat(39)}B`)
    expect(a).toMatch(/^[A-Za-z][A-Za-z0-9_]{31}$/)
    expect(b).toHaveLength(32)
    expect(a).not.toBe(b)
    expect(a).not.toBe(rapidName('WPS 1.2/A'))
  })
})

describe('toRapid', () => {
  it('writes the header, tool, work object and a template warning', () => {
    const text = toRapid(threeSeamJob())
    const head = lines(text)
    expect(head[0]).toMatch(/^MODULE WeldJob_wj_\d{8}_[a-z0-9]{4}$/)
    expect(text).toContain('! Template, verify on a controller before running.')
    expect(text).toContain('! Generated by ')
    expect(text).toContain('from double-bottom-cell.stl at 2026-11-04T10:15:00Z')
    expect(text).toContain('! Units mm; robtarget orientation [q1,q2,q3,q4] = [w,x,y,z]')
    expect(text).toContain('PERS tooldata tWeldGun := [TRUE,[[0,0,350],[1,0,0,0]],[3,[0,0,100],[1,0,0,0],0,0,0]];')
    expect(text).toContain('PERS wobjdata wPart := [FALSE,TRUE,"",[[0.0,0.0,0.0],[1.000000,0.000000,0.000000,0.000000]],[[0,0,0],[1,0,0,0]]];')
    expect(text.trimEnd().endsWith('ENDMODULE')).toBe(true)
  })

  it('emits one robtarget per pose of the standard and slim seams and none for the snake seam', () => {
    const job = threeSeamJob()
    const text = toRapid(job)
    const poseCount = (id: string) => job.seams.find((s) => s.id === id)!.poses.length
    const expected = poseCount('s01') + poseCount('s02')
    expect(targetLines(text)).toHaveLength(expected)
    expect(text).toMatch(/S01_P000 := \[\[\d/)
    expect(text).not.toContain('S03_')
    expect(text).toMatch(/! Not included: .*S03 \(s03, snake\)|! Not included: .*S03.*s03.*snake/)
  })

  it('writes one ArcLStart and one ArcLEnd per included seam and poses minus 2 ArcL', () => {
    const job = threeSeamJob()
    const text = toRapid(job)
    const poses = job.seams.filter((s) => s.id !== 's03').reduce((n, s) => n + s.poses.length, 0)
    expect(lines(text).filter((l) => l.startsWith('ArcLStart'))).toHaveLength(2)
    expect(lines(text).filter((l) => l.startsWith('ArcLEnd'))).toHaveLength(2)
    expect(lines(text).filter((l) => /^ArcL /.test(l))).toHaveLength(poses - 4)
    expect(lines(text).filter((l) => l.startsWith('MoveJ'))).toHaveLength(2)
    expect(lines(text).filter((l) => l.startsWith('MoveL'))).toHaveLength(2)
  })

  it('lists the seams in sequence order and starts a reversed seam at its own first pose', () => {
    const job = structuredClone(threeSeamJob())
    job.sequence.order = [
      { seamId: 's02', reversed: true },
      { seamId: 's01', reversed: false },
      { seamId: 's03', reversed: false },
    ]
    const second = job.seams.find((s) => s.id === 's02')!
    second.poses = [...second.poses].reverse().map((p, i) => ({ ...p, s: i }))
    const text = toRapid(job)
    const comments = lines(text).filter((l) => /^! S\d\d = /.test(l))
    expect(comments[0]).toContain('S01 = ')
    expect(comments[0]).toContain('(s02)')
    expect(comments[1]).toContain('(s01)')
    const first = targetLines(text)[0]!
    const [x, y] = second.poses[0]!.position
    expect(first).toContain(`[[${x.toFixed(1)},${y.toFixed(1)},`)
  })

  it('prints unit quaternions and no en or em dash', () => {
    const text = toRapid(threeSeamJob())
    const quats = [...text.matchAll(/\],\[(-?\d+\.\d{6}),(-?\d+\.\d{6}),(-?\d+\.\d{6}),(-?\d+\.\d{6})\],\[0,0,0,0\]/g)]
    expect(quats.length).toBeGreaterThan(0)
    for (const m of quats) {
      const norm = Math.hypot(...m.slice(1).map(Number))
      expect(Math.abs(norm - 1)).toBeLessThan(1e-5)
    }
    expect(text).not.toMatch(new RegExp('[\\u2013\\u2014]'))
  })

  it('names the approach, retract, seam and weld data from the seam and its procedure', () => {
    const job = threeSeamJob()
    const text = toRapid(job)
    const p = rapidName(job.seams[0]!.procedureId)
    expect(text).toContain(`MoveJ RelTool(S01_P000,0,0,-${job.seams[0]!.approach.distanceMm.toFixed(1)}), v1000, z50, tWeldGun\\WObj:=wPart;`)
    expect(text).toContain(`ArcLStart S01_P000, v100, sm_${p}, wd_${p}, fine, tWeldGun\\WObj:=wPart;`)
    expect(text).toMatch(/ArcLEnd S01_P\d{3}, v100, sm_.*, wd_.*, fine, tWeldGun\\WObj:=wPart;/)
    expect(text).toContain(`! Define in the cell: seamdata sm_${p}; welddata wd_${p}`)
  })

  it('adds the weave data when the procedure weaves', () => {
    const job = structuredClone(threeSeamJob())
    job.procedures[0]!.weave.pattern = 'zigzag'
    const text = toRapid(job)
    const p = rapidName(job.procedures[0]!.id)
    expect(text).toContain(`ArcLStart S01_P000, v100, sm_${p}, wd_${p}\\Weave:=wv_${p}, fine, tWeldGun\\WObj:=wPart;`)
    expect(text).toContain(`weavedata wv_${p}`)
  })

  it('excludes blocked, unchecked and one pose seams with the reason', () => {
    const job = structuredClone(threeSeamJob(['standard', 'blocked', null]))
    job.seams.push({ ...structuredClone(job.seams[0]!), id: 's04', label: 'ONE', poses: [job.seams[0]!.poses[0]!] })
    job.sequence.order.push({ seamId: 's04', reversed: false })
    const text = toRapid(job)
    const note = lines(text).find((l) => l.startsWith('! Not included:'))!
    expect(note).toContain('s02, blocked')
    expect(note).toContain('s03, access not checked')
    expect(note).toContain('s04, fewer than 2 poses')
    expect(targetLines(text)).toHaveLength(job.seams[0]!.poses.length)
  })

  it('writes an empty main when nothing can be included', () => {
    const job = threeSeamJob(['snake', 'blocked', 'snake'])
    const text = toRapid(job)
    expect(targetLines(text)).toHaveLength(0)
    expect(text).toContain('! Not included: ')
    expect(text).toMatch(/PROC main\(\)\n(\s*!.*\n)*\s*ENDPROC/)
    expect(text).toContain('! Define in the cell: none')
  })

  it('writes Not included: none when every seam is included', () => {
    const job = threeSeamJob(['standard', 'slim', 'standard'])
    expect(toRapid(job)).toContain('! Not included: none')
    expect(includedIds(job)).toHaveLength(3)
  })

  it('keeps every identifier within 32 characters for a long procedure id', () => {
    const job = structuredClone(threeSeamJob())
    const longId = 'WPS 1.2/A '.repeat(5)
    job.procedures[0]!.id = longId
    for (const s of job.seams) s.procedureId = longId
    const names = toRapid(job).match(/\b(?:sm|wd|wv|WeldJob)_\w+/g)!
    for (const n of names) expect(n.length).toBeLessThanOrEqual(32)
  })
})
